export type Translate = (key: Key, values?: Record<string, string | number>) => string;
export function translator(language: Language): Translate {
  return (key, values = {}) =>
    dictionaries[language][key].replace(/\{(\w+)\}/g, (_, k) => String(values[k] ?? ''));
}
export const isLanguage = (s: unknown): s is Language => s === 'en' || s === 'mr' || s === 'hi';
